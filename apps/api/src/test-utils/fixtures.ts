import bcrypt from "bcryptjs";
import { prisma, PrismaUserRepository, PrismaCredentialRepository } from "@trading/database";
import type { DecisionEventType, Portfolio, User } from "@trading/domain";
import { PrismaPortfolioRepository } from "@trading/database";

const userRepository = new PrismaUserRepository();
const credentialRepository = new PrismaCredentialRepository();
const portfolioRepository = new PrismaPortfolioRepository();

const TEST_PASSWORD = "correct-horse-battery-staple";

export interface TestUser {
  user: User;
  password: string;
}

/**
 * Creates a user with a real, login-able credential directly through
 * the repositories — there is no registration endpoint yet (deferred
 * to Phase 4, RBAC), so integration tests seed identity this way
 * instead of going through HTTP.
 *
 * Each call uses a random email so tests can run concurrently without
 * unique-constraint collisions, matching the pattern already used by
 * the repository test suites (e.g. prisma-asset-repository.test.ts).
 */
export async function createTestUser(): Promise<TestUser> {
  const user = await userRepository.create({
    email: `test-${crypto.randomUUID()}@example.com`,
    displayName: "Integration Test User",
  });

  const passwordHash = await bcrypt.hash(TEST_PASSWORD, 10);
  await credentialRepository.create({ userId: user.id, passwordHash });

  return { user, password: TEST_PASSWORD };
}

/** Creates a portfolio owned by the given user, with sensible defaults. */
export async function createTestPortfolio(
  userId: string,
  overrides: { name?: string; baseCurrency?: string } = {},
): Promise<Portfolio> {
  return portfolioRepository.create({
    userId,
    name: overrides.name ?? "Integration Test Portfolio",
    baseCurrency: overrides.baseCurrency ?? "USD",
  });
}

export interface TestAssetHandle {
  id: string;
}

/** Creates a disposable asset with a unique symbol, for transaction tests. */
export async function createTestAsset(
  symbolPrefix = "TST",
  overrides: {
    name?: string;
    assetType?: "STOCK" | "ETF" | "CRYPTO" | "FOREX";
    currency?: string;
    exchange?: string;
    status?: "ACTIVE" | "INACTIVE";
  } = {},
): Promise<TestAssetHandle> {
  const asset = await prisma.asset.create({
    data: {
      symbol: `${symbolPrefix}-${crypto.randomUUID().slice(0, 8)}`,
      name: overrides.name ?? "Integration Test Asset",
      assetType: overrides.assetType ?? "STOCK",
      currency: overrides.currency ?? "USD",
      exchange: overrides.exchange ?? "MOCK",
      ...(overrides.status !== undefined ? { status: overrides.status } : {}),
    },
  });
  return { id: asset.id };
}

/**
 * Creates a notification for the given user directly through Prisma —
 * there is no public endpoint to create notifications (they are
 * generated by system events, not by API callers), so tests seed them
 * here. Pass `read: true` to create it already marked as read.
 */
export async function createTestNotification(
  userId: string,
  overrides: { title?: string; read?: boolean } = {},
): Promise<{ id: string }> {
  const row = await prisma.notification.create({
    data: {
      userId,
      type: "test.integration",
      title: overrides.title ?? "Integration test notification",
      message: "Created by an integration test.",
      severity: "INFO",
      ...(overrides.read === true ? { readAt: new Date() } : {}),
    },
  });
  return { id: row.id };
}

export interface TestDecisionEventInput {
  type: DecisionEventType;
  timestamp: Date;
  payload?: Record<string, string | number>;
}

/**
 * Creates a decision (with entry/target/stop prices in USD) and its
 * events directly through Prisma — there is no write endpoint for
 * decisions yet. Events are inserted in the order given, so tests can
 * pass them out of chronological order to verify the API sorts them.
 * Cascade deletes (Portfolio -> Decision -> DecisionEvent) mean
 * `cleanupTestData` needs no extra step for these rows.
 */
export async function createTestDecision(
  portfolioId: string,
  assetId: string,
  overrides: {
    title?: string;
    direction?: "LONG" | "SHORT" | "NEUTRAL";
    createdAt?: Date;
    events?: TestDecisionEventInput[];
  } = {},
): Promise<{ id: string }> {
  const decision = await prisma.decision.create({
    data: {
      portfolioId,
      assetId,
      title: overrides.title ?? "Integration test decision",
      thesis: "Created by an integration test.",
      direction: overrides.direction ?? "LONG",
      entryPrice: 150,
      targetPrice: 170,
      stopPrice: 140,
      currency: "USD",
      riskLevel: "MODERATE",
      createdAt: overrides.createdAt ?? new Date("2026-06-01T14:00:00Z"),
    },
  });

  for (const event of overrides.events ?? []) {
    await prisma.decisionEvent.create({
      data: {
        decisionId: decision.id,
        type: event.type,
        timestamp: event.timestamp,
        payload: event.payload ?? {},
      },
    });
  }

  return { id: decision.id };
}

